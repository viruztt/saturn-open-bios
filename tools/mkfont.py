def cell(rows):
    rows = [(r + ".....")[:5] for r in rows] + ["....."] * (7 - len(rows))
    grid = ["........"] + ["." + r + ".." for r in rows]  # 1px top/left margin
    out = []
    for r in grid:
        for x in range(0, 8, 2):
            hi = 1 if r[x] == "#" else 0
            lo = 1 if r[x + 1] == "#" else 0
            out.append(hi << 4 | lo)
    return out

here = os.path.dirname(os.path.abspath(__file__))
with open(os.path.join(here, "..", "src", "font.s"), "w") as f:
    f.write("! SPDX-License-Identifier: GPL-2.0-or-later\n! Generated by tools/mkfont.py - do not edit\n")
    f.write("        .section .rodata\n        .align  2\n        .global font_data\n"
            "        .global font_end\nfont_data:              ! chars 0x20-0x5F, 32 bytes each\n")
    for c in range(0x20, 0x60):
        data = cell(G[chr(c)])
        f.write("        .byte   " + ",".join("0x%02X" % b for b in data) + "   ! %r\n" % chr(c))
    f.write("font_end:\n")
